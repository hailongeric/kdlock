"""Cold readback of an immutable image whose direct CALLs were relocated.

Only generated-image bytes are read. Original helper instructions and arguments
are never inspected. The session owns the loaded provider; a temporary readonly
device reference retains its image storage until the read and registry recheck end.
No operation in this module belongs inside a timed worker interval.
"""
import hashlib
import os
from pathlib import Path
import struct

from bench_runtime import Failure, registry, require
from summarize import write_json


DIRECT = 16
SERVICES = {4: ('strcmp', 4), 5: ('strscpy_pad', 8)}


def relocate(upload, base, symbols):
    """Reconstruct expected generated bytes independently of the provider."""
    require(64 <= len(upload) <= 640 * 1024 and
            upload[9:16] == b'KDWB002' and upload[25:32] == b'KDWC002' and
            upload[41:45] == b'KDAB' and
            upload[45:47] == bytes((1, 2)), 'invalid direct-image header', 'DATA_ERROR')
    requirements = upload[47]
    require(requirements in (20, 24, 28), 'invalid direct-image requirements', 'DATA_ERROR')
    magic, start, count = struct.unpack_from('<8sII', upload, len(upload) - 16)
    require(magic == b'KDNC0001' and 0 < count <= 64 and start >= 48 and
            start + 16 * count == len(upload) - 16,
            'invalid direct-call relocation directory', 'DATA_ERROR')
    require(0xffffffff80000000 < base < 2**64 - len(upload),
            'invalid loaded image address', 'DATA_ERROR')
    result, rows, occupied, seen = bytearray(upload), [], set(), 0
    for index in range(count):
        offset, service, continuation = struct.unpack_from('<IIQ', upload, start + 16 * index)
        require(service in SERVICES and continuation != 0,
                'invalid direct-call service or continuation', 'DATA_ERROR')
        name, bit = SERVICES[service]
        require(requirements & bit and 48 <= offset <= start - 5 and
                upload[offset:offset + 5] == b'\xe8\0\0\0\0',
                'invalid private generated CALL relocation slot', 'DATA_ERROR')
        span = set(range(offset, offset + 5))
        require(not occupied & span, 'overlapping relocation slots', 'DATA_ERROR')
        occupied.update(span)
        seen |= bit
        target = symbols.get(name, 0)
        displacement = target - (base + offset + 5)
        require(target != 0 and -(2**31) <= displacement < 2**31,
                'direct-call target outside rel32 reach', 'DATA_ERROR')
        struct.pack_into('<i', result, offset + 1, displacement)
        rows.append(dict(offset=offset, service=service, symbol=name, target=target,
                         continuation=continuation, displacement=displacement))
    require(seen == requirements & 12,
            'direct-call services do not match image requirements', 'DATA_ERROR')
    return bytes(result), rows


def read_image(address, size):
    from elftools.elf.elffile import ELFFile
    with open('/proc/kcore', 'rb') as stream:
        elf = ELFFile(stream)
        for segment in elf.iter_segments():
            if segment['p_type'] != 'PT_LOAD':
                continue
            start, length = segment['p_vaddr'], segment['p_memsz']
            if start <= address and address + size <= start + length:
                stream.seek(segment['p_offset'] + address - start)
                data = stream.read(size)
                require(len(data) == size, 'short loaded image read', 'DATA_ERROR')
                return data
    raise Failure('DATA_ERROR', 'loaded image is outside captured kcore segments')


def capture(session_path, entry, image_path):
    upload = image_path.read_bytes()
    entry_direct = bool(entry['requirements'] & DIRECT)
    upload_direct = len(upload) >= 48 and bool(upload[47] & DIRECT)
    if not entry_direct and not upload_direct:
        return None
    require(entry_direct and upload_direct and entry['entry_abi'] == 1 and
            entry['requirements'] == upload[47] and
            entry['generation'] > 0, 'direct-image registry/header mismatch', 'DATA_ERROR')
    # Readonly device open retains the provider module without adding a writer.
    # Generated allocations remain alive until provider teardown. This
    # does not request a source-text pin for an unrelated virtual address.
    fd = os.open('/dev/kd_dev', os.O_RDONLY | os.O_CLOEXEC)
    try:
        before = registry()
        require(entry in before, 'image registry changed before readback', 'DATA_ERROR')
        wanted = {value[0] for value in SERVICES.values()}
        symbols = {}
        for line in Path('/proc/kallsyms').read_text().splitlines():
            fields = line.split()
            if len(fields) == 3 and fields[2] in wanted:
                require(fields[2] not in symbols, 'ambiguous original API symbol', 'DATA_ERROR')
                symbols[fields[2]] = int(fields[0], 16)
        expected, relocations = relocate(upload, entry['code'], symbols)
        loaded = read_image(entry['code'], len(upload))
        require(loaded == expected, 'loaded generated image differs after relocation', 'DATA_ERROR')
        require(registry() == before, 'image registry changed during readback', 'DATA_ERROR')
    finally:
        os.close(fd)
    relative = Path('loaded-images') / f"{entry['entry']:016x}-g{entry['generation']}.bin"
    destination = session_path / relative
    destination.parent.mkdir(exist_ok=True)
    if destination.exists():
        require(destination.read_bytes() == loaded,
                'immutable loaded image changed since prior readback', 'DATA_ERROR')
    else:
        destination.write_bytes(loaded)
    receipt = dict(path=str(relative), entry=entry['entry'], generation=entry['generation'],
                   base=entry['code'], bytes=len(loaded), requirements=upload[47],
                   uploaded_sha256=hashlib.sha256(upload).hexdigest(),
                   loaded_sha256=hashlib.sha256(loaded).hexdigest(),
                   relocations=relocations, byte_for_byte_match=True,
                   method='Live /proc/kcore read under readonly provider reference, outside worker timing')
    write_json(destination.with_suffix('.json'), receipt)
    return receipt
