#!/usr/bin/env python3
"""Read-only identity checks reject drift, omitted evidence and root confusion."""
import hashlib
import importlib.util
import json
from pathlib import Path
import tempfile
import unittest
from unittest import mock

ROOT = Path(__file__).resolve().parents[3]
SPEC = importlib.util.spec_from_file_location("linux70_identity", ROOT / "kernel_integration/linux70/verify.py")
identity = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(identity)


def sha(data):
    return hashlib.sha256(data).hexdigest()


class Linux70IdentityTests(unittest.TestCase):
    def setUp(self):
        temporary = tempfile.TemporaryDirectory(prefix="kd-linux70-identity-")
        self.addCleanup(temporary.cleanup)
        self.root = Path(temporary.name)
        self.source, self.build, self.bundle = [self.root / name for name in ("source", "build", "bundle")]
        for path in (self.source, self.build, self.bundle):
            path.mkdir()
        for name, value in (("SOURCE_ROOT", self.source), ("BUILD_ROOT", self.build),
                            ("SYSTEM_ROOT", self.root / "system"),
                            ("BASE_SOURCE", {"Makefile": sha(b"upstream"), "debian.master/changelog": sha(b"upstream")}),
                            ("ACQUISITION_SHA256", sha(b"receipt"))):
            patcher = mock.patch.object(identity, name, value)
            patcher.start()
            self.addCleanup(patcher.stop)
        self.expected_running = dict(release=identity.RELEASE, version="#fixture", machine="x86_64", build_id="abcd")
        patcher = mock.patch.object(identity, "build_identity", return_value=self.expected_running)
        patcher.start()
        self.addCleanup(patcher.stop)
        for name in identity.CORE_PATHS | set(identity.BASE_SOURCE):
            self.write(self.source / name, b"upstream")
        for name in identity.BUILD_FILES:
            self.write(self.build / name, b"build")
        config = "".join(f"{key}={value}\n" if value != "n" else f"# {key} is not set\n"
                         for key, value in identity.CONFIG_REQUIRED.items()).encode()
        self.write(self.build / ".config", config)
        self.write(self.build / "Makefile", (
            f"# Automatically generated by {self.source}/Makefile: don't edit\n"
            f"export KBUILD_OUTPUT = {self.build}\ninclude {self.source}/Makefile\n").encode())
        self.write(self.bundle / "guest.config", config)
        self.write(self.bundle / "source-acquisition.json", b"receipt")
        self.write(self.bundle / "core-kernel.patch", (ROOT / "kernel_integration/linux70/kernel.patch").read_bytes())
        self.manifest = dict(schema=2, source_root=str(self.source), build_root=str(self.build),
            source_package=identity.PACKAGE, source_archives=identity.SOURCE_ARCHIVES,
            source_scope="named core/MM inputs; not a complete source-tree audit",
            core_patch="core-kernel.patch", mmap=None,
            bundle_files={p.name: identity.digest_file(p) for p in self.bundle.iterdir()},
            source_files={name: identity.digest_file(self.source / name)
                          for name in identity.CORE_PATHS | set(identity.BASE_SOURCE)},
            build_files={name: identity.digest_file(self.build / name) for name in identity.BUILD_FILES},
            configuration=identity.config_values(self.build / ".config"), running=self.expected_running,
            runtime_policy=identity.runtime_policy("BOOT_IMAGE=/fixture nokaslr nopvspin", "none voluntary full (lazy)"),
            installed_files={}, installed_links={})
        for name in identity.installed_paths():
            prefix = Path(name).name.removesuffix("-" + identity.RELEASE)
            source = {"vmlinuz": "arch/x86/boot/bzImage", "config": ".config", "System.map": "System.map"}.get(prefix)
            data = (self.build / source).read_bytes() if source else b"initrd"
            self.write(identity.SYSTEM_ROOT / name, data)
            self.manifest["installed_files"][name] = sha(data)
        for name, target in (("build", self.build), ("source", self.source)):
            relative = f"lib/modules/{identity.RELEASE}/{name}"
            path = identity.SYSTEM_ROOT / relative
            path.parent.mkdir(parents=True, exist_ok=True)
            path.symlink_to(target)
            self.manifest["installed_links"][relative] = str(target)
        self.save()

    @staticmethod
    def write(path, data):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)

    def save(self):
        (self.bundle / "manifest.json").write_text(json.dumps(self.manifest))

    def test_distinct_source_build_and_installed_inputs_verified(self):
        result = identity.verify(self.bundle, self.build)
        self.assertEqual(result["schema"], 2)
        self.assertTrue(result["ok"])
        self.assertNotIn("runtime_policy_verified", result)
        self.assertEqual(result["source_root"], str(self.source))
        self.assertFalse((self.source / ".config").exists())

    def test_drift_in_each_independent_identity_fails(self):
        for path in (self.source / "kernel/kallsyms.c", self.build / "Module.symvers",
                     self.build / "include/generated/autoconf.h", self.build / ".config",
                     self.bundle / "core-kernel.patch",
                     identity.SYSTEM_ROOT / f"boot/initrd.img-{identity.RELEASE}"):
            with self.subTest(path=path):
                original = path.read_bytes()
                path.write_bytes(original + b"changed")
                with self.assertRaises(identity.BaselineError):
                    identity.verify(self.bundle, self.build)
                path.write_bytes(original)

    def test_source_build_confusion_and_symlink_alias_rejected(self):
        alias = self.root / "build-alias"
        alias.symlink_to(self.build, target_is_directory=True)
        for selected in (self.source, alias):
            with self.subTest(selected=selected), self.assertRaises(identity.BaselineError):
                identity.verify(self.bundle, selected)
        self.manifest["source_root"] = str(self.root / "other-source")
        self.save()
        with self.assertRaisesRegex(identity.BaselineError, "source root mismatch"):
            identity.verify(self.bundle, self.build)

    def test_generated_makefile_binding_cannot_be_replaced_by_manifest_hash(self):
        path = self.build / "Makefile"
        path.write_text(f"include {self.root}/different/Makefile\n")
        self.manifest["build_files"]["Makefile"] = identity.digest_file(path)
        self.save()
        with self.assertRaisesRegex(identity.BaselineError, "binding mismatch"):
            identity.verify(self.bundle, self.build)

    def test_missing_required_inputs_fail(self):
        for field, key in (("build_files", "include/generated/autoconf.h"),
                           ("source_files", "kernel/kallsyms.c"),
                           ("installed_files", f"boot/vmlinuz-{identity.RELEASE}")):
            saved = self.manifest[field].pop(key)
            self.save()
            with self.subTest(field=field), self.assertRaises(identity.BaselineError):
                identity.verify(self.bundle, self.build)
            self.manifest[field][key] = saved

    def test_overlay_cannot_be_unrecorded_even_if_disabled(self):
        self.write(self.source / "include/linux/kd_mmap_lock.h", b"overlay")
        with self.assertRaisesRegex(identity.BaselineError, "requires preparation"):
            identity.verify(self.bundle, self.build)

    def test_partial_overlay_cannot_bypass_preparation_identity(self):
        (self.source / "kernel/locking/kd_mmap").mkdir(parents=True)
        with self.assertRaisesRegex(identity.BaselineError, "requires preparation"):
            identity.verify(self.bundle, self.build)

    def test_mm_preparation_receipt_must_itself_be_hashed(self):
        self.write(self.source / "include/linux/kd_mmap_lock.h", b"overlay")
        self.manifest["mmap"] = dict(enabled=False)
        self.save()
        with self.assertRaisesRegex(identity.BaselineError, "provenance files omitted"):
            identity.verify(self.bundle, self.build)

    def test_module_header_link_cannot_point_to_another_tree(self):
        path = identity.SYSTEM_ROOT / f"lib/modules/{identity.RELEASE}/build"
        path.unlink()
        path.symlink_to(self.source)
        with self.assertRaisesRegex(identity.BaselineError, "header/source link mismatch"):
            identity.verify(self.bundle, self.build)

    def test_absent_optional_installed_source_link_is_valid(self):
        name = f"lib/modules/{identity.RELEASE}/source"
        (identity.SYSTEM_ROOT / name).unlink()
        del self.manifest["installed_links"][name]
        self.save()
        self.assertTrue(identity.verify(self.bundle, self.build)["ok"])

    def test_rehashed_installed_image_must_still_match_build(self):
        name = f"boot/vmlinuz-{identity.RELEASE}"
        path = identity.SYSTEM_ROOT / name
        path.write_bytes(b"different image")
        self.manifest["installed_files"][name] = identity.digest_file(path)
        self.save()
        with self.assertRaisesRegex(identity.BaselineError, "installed/build identity mismatch"):
            identity.verify(self.bundle, self.build)

    def test_runtime_policy_matches_exact_command_line_and_active_mode(self):
        expected = self.manifest["runtime_policy"]
        self.assertEqual(identity.check_runtime(expected, expected["cmdline"], "none voluntary full (lazy)\n"), expected)
        for cmdline, preempt in (("nokaslr nopvspin extra=1", "none voluntary full (lazy)"),
                                 (expected["cmdline"], "none (voluntary) full lazy"),
                                 ("nokaslr", "none voluntary full (lazy)"),
                                 ("nokaslr nopvspin preempt=voluntary", "none voluntary full (lazy)")):
            with self.subTest(cmdline=cmdline, preempt=preempt), self.assertRaises(identity.BaselineError):
                identity.check_runtime(expected, cmdline, preempt)


if __name__ == "__main__":
    unittest.main()
